package io.nettix.util;

/**
 * Defines various commonly used character constants.
 *
 * @author sanha
 */
public class Character
{
    /**
     * Left parenthesis '(' character.
     */
    public static final char LEFT_PAREN = '(';

    /**
     * Right parenthesis ')' character.
     */
    public static final char RIGHT_PAREN = ')';

    /**
     * Left brace '{' character.
     */
    public static final char LEFT_BRACE = '{';

    /**
     * Right brace '}' character.
     */
    public static final char RIGHT_BRACE = '}';

    /**
     * Left bracket '[' character.
     */
    public static final char LEFT_BRACKET = '[';

    /**
     * Right bracket ']' character.
     */
    public static final char RIGHT_BRACKET = ']';

    /**
     * Carriage return character.
     */
    public static final char CR = '\r';

    /**
     * Line feed (newline) character.
     */
    public static final char LF = '\n';

    /**
     * Tab character.
     */
    public static final char TAB = '\t';

    /**
     * Period '.' character.
     */
    public static final char PERIOD = '.';

    /**
     * Comma ',' character.
     */
    public static final char COMMA = ',';

    /**
     * Single quote '\'' character.
     */
    public static final char SINGLE_QUOTA = '\'';

    /**
     * Double quote '"' character.
     */
    public static final char DOUBLE_QUOTA = '"';

    /**
     * Colon ':' character.
     */
    public static final char COLON = ':';

    /**
     * Semicolon ';' character.
     */
    public static final char SEMI_COLON = ';';

    /**
     * Equals '=' character.
     */
    public static final char EQUAL = '=';

    /**
     * Space ' ' character.
     */
    public static final char SPACE = ' ';

    /**
     * Hyphen '-' character.
     */
    public static final char HYPEN = '-';

}